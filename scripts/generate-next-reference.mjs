#!/usr/bin/env node
// Generates MDX partials for the ErsatzTV Next reference from schemas/next/ (see sync-next-schemas.mjs),
// a redirect page for every known schema version URL (static/{kind}/version/{x.y.z}/index.html), and
// _generated/versions.json with the current and known versions of each kind.
//
// Usage: node scripts/generate-next-reference.mjs
//
// Writes docs-next/reference/_generated/{kind}/{Definition}.mdx, one per schema definition plus one
// for the root (named by the schema's title). Docusaurus doesn't publish `_` folders; the reference
// pages import the partials. Type links point to `#{definition}` in lowercase, so a page that
// includes a definition gives its heading that id, e.g. `### StreamMode {#streammode}`.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { KINDS, definitions, versionTarget } from "./lib/next-schema.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaFolder = join(root, "schemas", "next");
const outFolder = join(root, "docs-next", "reference", "_generated");
// one page per known schema version, so version URLs return 200; src/theme/NotFound handles the rest
const versionPageFolder = (kind) => join(root, "static", kind, "version");

const HEADER = "{/* Generated by scripts/generate-next-reference.mjs from schemas/next/. Do not edit. */}\n";

// MDX reads `{` and `<` as JSX outside code spans; tables also need `|` escaped inside them
function escapeText(text, { table }) {
  return text
    .split(/(`+[^`]*?`+)/)
    .map((part, i) => {
      if (i % 2 === 1) return table ? part.replaceAll("|", "\\|") : part;
      let escaped = part.replaceAll("{", "&#123;").replaceAll("}", "&#125;").replaceAll("<", "&lt;");
      if (table) escaped = escaped.replaceAll("|", "\\|");
      return escaped;
    })
    .join("");
}

function cell(text) {
  if (!text) return "";
  const paragraphs = text.trim().split(/\n\s*\n/).map((p) => p.replace(/\s*\n\s*/g, " "));
  return escapeText(paragraphs.join("<br/><br/>"), { table: true });
}

function paragraph(text) {
  return text ? escapeText(text.trim(), { table: false }) + "\n\n" : "";
}

const code = (value) => "`" + String(value).replaceAll("|", "\\|") + "`";
const anchor = (name) => name.toLowerCase();
const refName = (ref) => ref.split("/").pop();
const isNull = (n) => n.type === "null" || n.const === null;

function scalarType(n) {
  const types = (Array.isArray(n.type) ? n.type : [n.type]).filter((t) => t && t !== "null");
  return types.join(" or ");
}

function typeOf(n) {
  if (!n || typeof n !== "object") return "";
  if (n.$ref) return `[${code(refName(n.$ref))}](#${anchor(refName(n.$ref))})`;
  if (n.const !== undefined) return code(JSON.stringify(n.const));

  for (const keyword of ["anyOf", "oneOf"]) {
    if (n[keyword]) {
      const branches = n[keyword].filter((b) => !isNull(b));
      if (branches.every((b) => b.const !== undefined)) return enumType(branches.map((b) => b.const));
      return branches.map(typeOf).join(" or ");
    }
  }

  if (Array.isArray(n.enum)) return enumType(n.enum);
  if (scalarType(n) === "array" || n.items) return `array of ${typeOf(n.items) || "any"}`;
  return code(scalarType(n) || "any");
}

function enumType(values) {
  return "one of " + values.filter((v) => v !== null).map((v) => code(JSON.stringify(v))).join(", ");
}

function sinceCell(since, key) {
  const entry = since.items[key];
  if (!entry) throw new Error(`since.json has no entry for ${key}; run scripts/sync-next-schemas.mjs`);
  return entry.release ? entry.version : `${entry.version} (unreleased)`;
}

// enum values as [value, description]; a plain `enum` has no description per value
function enumValues(n) {
  if (Array.isArray(n.enum)) return n.enum.filter((v) => v !== null).map((v) => [v, ""]);
  const branches = n.oneOf ?? n.anyOf;
  if (branches?.length && branches.every((b) => b.const !== undefined)) {
    return branches.filter((b) => b.const !== null).map((b) => [b.const, b.description ?? ""]);
  }
  return null;
}

function renderDefinition(name, n, since) {
  let out = HEADER + "\n" + paragraph(n.description);

  const values = enumValues(n);
  if (values) {
    const described = values.some(([, description]) => description);
    out += described ? "| Value | Since | Description |\n|---|---|---|\n" : "| Value | Since |\n|---|---|\n";
    for (const [value, description] of values) {
      const row = [code(value), sinceCell(since, `${name}=${value}`)];
      if (described) row.push(cell(description));
      out += `| ${row.join(" | ")} |\n`;
    }
    return out;
  }

  if (n.properties) {
    const required = new Set(n.required ?? []);
    out += "| Property | Type | Default | Since | Description |\n|---|---|---|---|---|\n";
    for (const [property, p] of Object.entries(n.properties)) {
      const key = `${name}.${property}`;
      out += `| ${[
        code(property) + (required.has(property) ? " (required)" : ""),
        typeOf(p),
        p.default === undefined ? "" : code(JSON.stringify(p.default)),
        sinceCell(since, key),
        cell(p.description),
      ].join(" | ")} |\n`;
    }
    return out;
  }

  // a union of definitions, e.g. a source or timing type
  const branches = (n.oneOf ?? n.anyOf ?? []).filter((b) => !isNull(b));
  if (branches.length) {
    out += "One of:\n\n" + branches.map((b) => `- ${typeOf(b)}`).join("\n") + "\n";
    return out;
  }

  return out + `Type: ${typeOf(n)}\n`;
}

const sinceFile = JSON.parse(readFileSync(join(schemaFolder, "since.json"), "utf8"));

rmSync(outFolder, { recursive: true, force: true });

let count = 0;
for (const { kind, file } of KINDS) {
  const schema = JSON.parse(readFileSync(join(schemaFolder, file), "utf8"));
  const since = sinceFile.schemas[kind];
  const folder = join(outFolder, kind);
  mkdirSync(folder, { recursive: true });

  const { $defs, definitions: _, ...rootDefinition } = schema;
  const all = [[schema.title, rootDefinition], ...Object.entries(definitions(schema))];
  for (const [name, n] of all) {
    writeFileSync(join(folder, `${name}.mdx`), renderDefinition(name, n, since));
    count++;
  }
}

function versionPage(kind, version) {
  const target = versionTarget(kind, version);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>ErsatzTV Next ${kind} version ${version}</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="https://ersatztv.org${target}">
<meta http-equiv="refresh" content="0; url=${target}">
<script>location.replace(${JSON.stringify(target)} + location.hash);</script>
</head>
<body>
<p><a href="${target}">ErsatzTV Next ${kind} version ${version}</a></p>
</body>
</html>
`;
}

// for src/components/NextVersionBanner, which compares a file's version with the docs
const versions = {};
for (const { kind } of KINDS) {
  const { version, versions: known } = sinceFile.schemas[kind];
  versions[kind] = { current: version, known: Object.keys(known) };
}
writeFileSync(join(outFolder, "versions.json"), JSON.stringify(versions, null, 2) + "\n");

let pages = 0;
for (const { kind } of KINDS) {
  rmSync(versionPageFolder(kind), { recursive: true, force: true });
  for (const version of Object.keys(sinceFile.schemas[kind].versions)) {
    const folder = join(versionPageFolder(kind), version);
    mkdirSync(folder, { recursive: true });
    writeFileSync(join(folder, "index.html"), versionPage(kind, version));
    pages++;
  }
}

console.log(`wrote ${count} partials to ${outFolder} and ${pages} version pages to static/`);
